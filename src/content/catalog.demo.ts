/**
 * Deterministic demo stock, so sold-out and low-stock states always exist to look at. It
 * hashes the variant key, which means a re-seed gives the same numbers.
 */
export function demoStock(handle: string, colorSlug: string, size: string): number {
  let hash = 7;
  for (const char of `${handle}/${colorSlug}/${size}`) hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
  const bucket = hash % 10;
  if (bucket === 0) return 0;
  if (bucket <= 2) return 2;
  return 6 + (hash >> 8) % 9;
}
